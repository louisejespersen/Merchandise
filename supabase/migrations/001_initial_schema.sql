-- Slå RLS til på alle tabeller, der eksponeres via Data API.
alter table public.products enable row level security;
alter table public.admin_users enable row level security;
alter table public.orders enable row level security;

-- Fjern brede standardrettigheder og giv kun det, appen bruger.
revoke all on table public.products from anon, authenticated;
revoke all on table public.admin_users from anon, authenticated;
revoke all on table public.orders from anon, authenticated;

-- Offentlig formular: må læse aktive varenumre og indsætte en ordre, men ikke læse ordrer.
grant select on table public.products to anon;
grant insert (customer_name, phone_number, product_number, shirt_size, print_text, prepaid)
  on table public.orders to anon;
grant usage, select on sequence public.orders_id_seq to anon;

-- Loggede brugere kan læse deres egen admin-markering. Selve tabellen kan kun ændres fra SQL-editoren.
grant select on table public.admin_users to authenticated;

-- Loggede brugere kan se aktive produkter; administratorer kan også se deaktiverede og administrere listen.
grant select, insert (product_number, is_active), update (is_active)
  on table public.products to authenticated;

-- Kun administratorer kan læse og ændre ordrer. Insert er også tilladt for loggede administratorer,
-- så ordreformularen fortsat virker, hvis en administrator allerede er logget ind i samme browser.
grant select on table public.orders to authenticated;
grant insert (customer_name, phone_number, product_number, shirt_size, print_text, prepaid)
  on table public.orders to authenticated;
grant update (customer_name, phone_number, product_number, shirt_size, print_text, prepaid, delivered)
  on table public.orders to authenticated;
grant usage, select on sequence public.orders_id_seq to authenticated;

-- En bruger kan kun se sin egen række i admin-listen.
drop policy if exists "admins can read own membership" on public.admin_users;
create policy "admins can read own membership"
on public.admin_users for select
to authenticated
using (user_id = (select auth.uid()));

-- Offentlig ordreformular må kun læse aktive varenumre.
drop policy if exists "public can read active products" on public.products;
create policy "public can read active products"
on public.products for select
to anon
using (is_active = true);

-- Indloggede brugere ser aktive produkter; administratorer ser også de deaktiverede.
drop policy if exists "authenticated can read products" on public.products;
create policy "authenticated can read products"
on public.products for select
to authenticated
using (
  is_active = true
  or exists (select 1 from public.admin_users au where au.user_id = (select auth.uid()))
);

-- Kun godkendte administratorer kan tilføje og deaktivere/aktivere varenumre.
drop policy if exists "admins can insert products" on public.products;
create policy "admins can insert products"
on public.products for insert
to authenticated
with check (exists (select 1 from public.admin_users au where au.user_id = (select auth.uid())));

drop policy if exists "admins can update products" on public.products;
create policy "admins can update products"
on public.products for update
to authenticated
using (exists (select 1 from public.admin_users au where au.user_id = (select auth.uid())))
with check (exists (select 1 from public.admin_users au where au.user_id = (select auth.uid())));

-- Formularen må indsætte, men ikke læse eller ændre ordredata.
drop policy if exists "public can submit orders" on public.orders;
create policy "public can submit orders"
on public.orders for insert
to anon, authenticated
with check (true);

-- Administratorer kan læse og opdatere alle ordrer.
drop policy if exists "admins can read orders" on public.orders;
create policy "admins can read orders"
on public.orders for select
to authenticated
using (exists (select 1 from public.admin_users au where au.user_id = (select auth.uid())));

drop policy if exists "admins can update orders" on public.orders;
create policy "admins can update orders"
on public.orders for update
to authenticated
using (exists (select 1 from public.admin_users au where au.user_id = (select auth.uid())))
with check (exists (select 1 from public.admin_users au where au.user_id = (select auth.uid())));

