create table if not exists public.products (
  product_number text primary key,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint product_number_not_blank check (length(trim(product_number)) between 1 and 20)
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  added_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  phone_number text not null,
  product_number text not null references public.products(product_number) on update cascade on delete restrict,
  shirt_size text not null,
  print_text text not null,
  prepaid boolean not null default false,
  delivered boolean not null default false,
  created_at timestamptz not null default now(),
  delivered_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint customer_name_not_blank check (length(trim(customer_name)) between 1 and 100),
  constraint phone_number_not_blank check (length(trim(phone_number)) between 1 and 30),
  constraint valid_shirt_size check (shirt_size in ('XS', 'S', 'M', 'L', 'XL', 'XXL')),
  constraint print_text_max_nine_characters check (char_length(print_text) between 1 and 9)
);

create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_delivered_idx on public.orders (delivered);

-- Sæt tidsstempler på serversiden, så klienten ikke selv kan bestemme dem.
create or replace function public.set_order_timestamps()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  if tg_op = 'UPDATE' then
    if new.delivered = true and old.delivered = false then
      new.delivered_at := now();
    elsif new.delivered = false then
      new.delivered_at := null;
    else
      new.delivered_at := old.delivered_at;
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists orders_set_timestamps on public.orders;
create trigger orders_set_timestamps
before insert or update on public.orders
for each row execute function public.set_order_timestamps();

